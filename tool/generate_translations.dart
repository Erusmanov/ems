import 'dart:convert';
import 'dart:io';

/// Run `dart run tool/generate_translations.dart` after editing lib/l10n/*.json.
void main() {
  const codes = ['ru', 'en', 'de', 'fr', 'es', 'it', 'tr', 'el', 'hr'];
  final translations = <String, dynamic>{};
  final placeholders = RegExp(r'\{\d+\}');
  for (final code in codes) {
    translations[code] = jsonDecode(
      File('lib/l10n/$code.json').readAsStringSync(),
    );
  }
  final source = translations['ru'] as Map<String, dynamic>;
  for (final code in codes) {
    final values = translations[code] as Map<String, dynamic>;
    if (values.length != source.length ||
        !values.keys.toSet().containsAll(source.keys)) {
      throw StateError('Incomplete catalogue: $code');
    }
    for (final key in source.keys) {
      final expected = placeholders
          .allMatches(source[key] as String)
          .map((m) => m[0])
          .toSet();
      final actual = placeholders
          .allMatches(values[key] as String)
          .map((m) => m[0])
          .toSet();
      if (expected.length != actual.length || !actual.containsAll(expected)) {
        throw StateError('Placeholder mismatch: $code/$key');
      }
    }
  }
  final sourceKeys = jsonDecode(
    File('lib/l10n/source_keys.json').readAsStringSync(),
  );
  String literal(Object value) =>
      const JsonEncoder.withIndent('  ').convert(value).replaceAll(r'$', r'\$');
  File('lib/l10n/messages.dart').writeAsStringSync(
    '// Generated by tool/generate_translations.dart. Edit the JSON catalogues.\n'
    'const messages = ${literal(translations)};\n'
    'const sourceKeys = ${literal(sourceKeys)};\n',
  );
}
